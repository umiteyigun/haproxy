def run_port_manager():
    log("Starting Port Manager (IPTables Mode)...")
    if not os.path.exists(PORTS_FILE_DIR):
        try:
            os.makedirs(PORTS_FILE_DIR)
        except:
            pass

    while True:
        try:
            # 1. Read desired ports from file(s) generated by API
            desired_ports = set()
            
            # Helper: Always keep these open
            desired_ports.add("80/tcp")
            desired_ports.add("443/tcp")
            desired_ports.add("8404/tcp")
            desired_ports.add("30000-30100/tcp") 
            desired_ports.add("21/tcp")
            
            # Read from file created by API
            port_files = glob.glob(os.path.join(PORTS_FILE_DIR, "*.txt"))
            for p_file in port_files:
                with open(p_file, 'r') as f:
                    for line in f:
                        line = line.strip()
                        if line:
                            desired_ports.add(line)

            # 2. Get currently open ports
            current_ports = get_open_ports()

            # 3. Open missing ports
            for port in desired_ports:
                if port not in current_ports:
                    open_port(port)

        except Exception as e:
            log(f"Error in cycle: {e}")
        
        time.sleep(10)

